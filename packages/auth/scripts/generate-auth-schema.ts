import { spawn } from "node:child_process";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { relations as dbRelations } from "@photon/db";
import { Project, SyntaxKind } from "ts-morph";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const authPackageDir = resolve(scriptDir, "..");
const repoRoot = resolve(authPackageDir, "../..");

const pgCoreImport =
    /^import\s*{([^}]*)}\s*from\s*["']drizzle-orm\/pg-core["'];/m;
const pgTableFactory =
    "const pgTable = pgTableCreator((name) => `auth_${name}`);";

const outputPath = resolve(authPackageDir, "../db/src/schema/auth.ts");
const cliOutputPath = relative(authPackageDir, outputPath);

// Pinned so the schema is generated by the better-auth we actually run.
const betterAuthVersion = (
    createRequire(import.meta.url)("better-auth/package.json") as {
        version: string;
    }
).version;

await mkdir(dirname(outputPath), { recursive: true });
await run(
    "bunx",
    [
        "--bun",
        `auth@${betterAuthVersion}`,
        "generate",
        "-y",
        "--config",
        "./src/cli-auth-instance.ts",
        "--output",
        cliOutputPath,
    ],
    { cwd: authPackageDir },
);

const generatedSchema = await readFile(outputPath, "utf8");
await writeFile(
    outputPath,
    addAuthTablePrefix(stripLegacyRelations(generatedSchema)),
);

await run("bunx", ["oxfmt", outputPath], { cwd: repoRoot });

/**
 * The CLI emits `relations()` calls, which drizzle 1.0 no longer exports. The
 * relations live in `packages/db/src/relations.ts`, so they are dropped here,
 * and the generator fails rather than lose one the CLI asked for.
 */
function stripLegacyRelations(source: string) {
    const file = new Project({
        useInMemoryFileSystem: true,
    }).createSourceFile("auth.ts", source);
    const missing: string[] = [];

    for (const statement of file.getVariableStatements()) {
        const call = statement
            .getDeclarations()[0]
            ?.getInitializerIfKind(SyntaxKind.CallExpression);
        if (call?.getExpression().getText() !== "relations") continue;

        const [table, builder] = call.getArguments();
        const body = builder
            ?.asKind(SyntaxKind.ArrowFunction)
            ?.getBody()
            .asKind(SyntaxKind.ParenthesizedExpression)
            ?.getExpressionIfKind(SyntaxKind.ObjectLiteralExpression);
        if (!table || !body) {
            throw new Error(
                `Could not read the generated relations: ${statement.getText()}`,
            );
        }

        const tableName = table.getText();
        const defined = (
            dbRelations as Record<
                string,
                { relations: Record<string, unknown> } | undefined
            >
        )[tableName]?.relations;
        for (const property of body.getProperties()) {
            const name = property
                .asKindOrThrow(SyntaxKind.PropertyAssignment)
                .getName();
            if (!defined?.[name]) missing.push(`${tableName}.${name}`);
        }
        statement.remove();
    }

    if (missing.length > 0) {
        throw new Error(
            `better-auth generated relations that packages/db/src/relations.ts does not define: ${missing.join(", ")}. Add them there.`,
        );
    }

    file.getImportDeclaration(
        (declaration) =>
            declaration.getModuleSpecifierValue() === "drizzle-orm" &&
            declaration.getNamedImports().length === 1 &&
            declaration.getNamedImports()[0]?.getName() === "relations",
    )?.remove();

    return file.getFullText();
}

function addAuthTablePrefix(source: string) {
    const importMatch = source.match(pgCoreImport);

    if (!importMatch) {
        throw new Error('Could not find the "drizzle-orm/pg-core" import.');
    }

    const importedSpecifiers = importMatch[1];

    if (!importedSpecifiers) {
        throw new Error('Could not read the "drizzle-orm/pg-core" import.');
    }

    const specifiers = importedSpecifiers
        .split(",")
        .map((specifier) => specifier.trim())
        .filter((specifier) => specifier.length > 0 && specifier !== "pgTable");

    if (!specifiers.includes("pgTableCreator")) {
        specifiers.push("pgTableCreator");
    }

    let updated = source.replace(
        pgCoreImport,
        [
            "import {",
            ...specifiers.map((specifier) => `    ${specifier},`),
            '} from "drizzle-orm/pg-core";',
        ].join("\n"),
    );

    if (updated.includes(pgTableFactory)) {
        return updated;
    }

    const importBlock = updated.match(/^(?:import[\s\S]*?;\n)+/);

    if (!importBlock) {
        throw new Error("Could not find the import block.");
    }

    return [
        importBlock[0],
        pgTableFactory,
        "",
        updated.slice(importBlock[0].length),
    ].join("\n");
}

function run(command: string, args: string[], options: { cwd: string }) {
    return new Promise<void>((resolveCommand, rejectCommand) => {
        const child = spawn(command, args, {
            cwd: options.cwd,
            stdio: "inherit",
        });

        child.on("error", rejectCommand);
        child.on("exit", (code, signal) => {
            if (code === 0) {
                resolveCommand();
                return;
            }

            rejectCommand(
                new Error(
                    `${command} ${args.join(" ")} failed with ${
                        signal ? `signal ${signal}` : `exit code ${code}`
                    }.`,
                ),
            );
        });
    });
}

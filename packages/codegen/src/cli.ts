#!/usr/bin/env bun
/**
 * Generates TypeScript types for the Photon API from its OpenAPI document.
 *
 * openapi-typescript needs the TypeScript compiler API, which TypeScript 7
 * does not ship yet. This package aliases `typescript` to
 * `@typescript/typescript6` so the rest of the repo can stay on 7. Drop the
 * alias once openapi-typescript runs on TypeScript 7.
 *
 * ### Usage
 *
 *     photon-codegen <output-dir>
 */
import { mkdir, mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import openapiTS, { COMMENT_HEADER, astToString } from "openapi-typescript";

const GENERATED_HEADER =
    "// This file is auto-generated by `bun run codegen`.\n// Do not edit this file directly.\n\n";

const API_DIR = resolve(import.meta.dir, "../../../apps/api");

const [outArg] = process.argv.slice(2);
if (!outArg) {
    throw new Error("Usage: photon-codegen <output-dir>");
}
const outDir = resolve(process.cwd(), outArg);

async function loadSpec(): Promise<string> {
    const tmp = await mkdtemp(join(tmpdir(), "photon-codegen-"));
    const specPath = join(tmp, "openapi.json");
    try {
        const proc = Bun.spawnSync(
            ["bun", "run", "src/scripts/openapi-spec.ts", specPath],
            { cwd: API_DIR, stdout: "ignore", stderr: "inherit" },
        );
        if (proc.exitCode !== 0) {
            throw new Error(
                `Failed to build OpenAPI spec (exit code ${proc.exitCode})`,
            );
        }
        return await readFile(specPath, "utf-8");
    } finally {
        await rm(tmp, { recursive: true, force: true });
    }
}

function toTypeName(name: string): string {
    const pascal = name
        .replace(/([a-z0-9])([A-Z])/g, "$1 $2")
        .replace(/[^a-zA-Z0-9]+/g, " ")
        .trim()
        .split(/\s+/)
        .filter(Boolean)
        .map((word) => `${word.charAt(0).toUpperCase()}${word.slice(1)}`)
        .join("");

    const base = pascal || "Schema";
    return /^[0-9]/.test(base) ? `Schema${base}` : base;
}

function schemaAliases(spec: Record<string, unknown>): string {
    const schemas =
        (spec as { components?: { schemas?: Record<string, unknown> } })
            .components?.schemas ?? {};
    const keys = Object.keys(schemas).sort((a, b) => a.localeCompare(b));

    const usedNames = new Set<string>();
    const aliases = keys.map((key) => {
        const rawName = toTypeName(key);
        let alias = rawName;
        for (let counter = 2; usedNames.has(alias); counter++) {
            alias = `${rawName}${counter}`;
        }
        usedNames.add(alias);
        return `\nexport type ${alias} = Schemas[${JSON.stringify(key)}];`;
    });

    return `${GENERATED_HEADER}import type { components } from "./openapi";

export type Schemas = components["schemas"];
export type SchemaNames = keyof Schemas;
export type SchemaOf<TName extends SchemaNames> = Schemas[TName];
${aliases.join("")}
`;
}

const specJson = await loadSpec();
const ast = await openapiTS(specJson);

await mkdir(outDir, { recursive: true });
await writeFile(
    join(outDir, "openapi.ts"),
    `${COMMENT_HEADER}${astToString(ast)}`,
);
await writeFile(
    join(outDir, "schemas.ts"),
    schemaAliases(JSON.parse(specJson)),
);
await writeFile(
    join(outDir, "index.ts"),
    `${GENERATED_HEADER}export type * from "./openapi";\nexport type * from "./schemas";\n`,
);

console.log(`OpenAPI types generated in ${outDir}`);

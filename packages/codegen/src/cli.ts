/** Generate the Photon client and transport with typed-openapi, without running services. */
import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { generateClientFiles } from "typed-openapi/node";

const outDir = resolve(import.meta.dir, "generated");
const tmp = await mkdtemp(join(tmpdir(), "photon-codegen-"));
try {
    const specPath = join(tmp, "openapi.json");
    const proc = Bun.spawnSync(
        ["bun", "run", "src/scripts/openapi-spec.ts", specPath],
        {
            cwd: resolve(import.meta.dir, "../../../apps/api"),
            stdout: "ignore",
            stderr: "inherit",
        },
    );
    if (proc.exitCode !== 0) {
        throw new Error(
            `Failed to build OpenAPI spec (exit code ${proc.exitCode})`,
        );
    }
    await generateClientFiles(specPath, {
        output: join(outDir, "openapi.ts"),
        runtime: "none",
        defaultFetcher: { clientPath: "./openapi" },
        format: true,
        // Proxies and middleware can return statuses absent from individual routes.
        errorStatusCodes: Array.from({ length: 200 }, (_, i) => 400 + i).join(
            ",",
        ),
    });
    await writeFile(
        join(outDir, "index.ts"),
        `// Generated by photon-codegen. Do not edit.
import type { EndpointByMethod } from "./openapi";
export * from "./openapi";
export { defaultFetcher, createApi } from "./api.client";

type ParameterOf<T, K extends string> = T extends { parameters: infer P }
    ? K extends keyof P ? NonNullable<P[K]> : never
    : never;
export type QueryParamsHelper<
    M extends keyof EndpointByMethod,
    P extends keyof EndpointByMethod[M],
> = ParameterOf<EndpointByMethod[M][P], "query">;
export type RequestBodyHelper<
    M extends keyof EndpointByMethod,
    P extends keyof EndpointByMethod[M],
> = ParameterOf<EndpointByMethod[M][P], "body">;
`,
    );
} finally {
    await rm(tmp, { recursive: true, force: true });
}
